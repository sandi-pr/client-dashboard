	if !ok {
		return ctx.Error(400, "invalid parameters")
	}

	total_amount, ok := ctx.Params.GetFloat64("total_amount")

	if !ok {
		return ctx.Error(400, "invalid parameters")
	}

	fmt.Println("invoice.go", total_amount)

	person, ok := ctx.Params.GetFloat64("person")

	if !ok {
		return ctx.Error(400, "invalid parameters")
	}

	invoice_date, ok := ctx.Params.GetString("invoice_date")

	if !ok {
		return ctx.Error(400, "invalid parameters")
	}

	due_date, ok := ctx.Params.GetString("due_date")

	if !ok {
		return ctx.Error(400, "invalid parameters")
	}

	payment_statusStr, ok := ctx.Params.GetString("payment_status")

	if !ok {
		return ctx.Error(400, "invalid parameters")
	}

	var payment_status interface{}
	err = json.Unmarshal([]byte(payment_statusStr), &payment_status)

	if err != nil {
		return ctx.Error(400, "invalid availability format")
	}

	status, invoice, err := Strapi.Create("invoice-table", U.Dict{
		"order_booking":  order_booking,
		"total_amount":   total_amount,
		"person":         person,
		"invoice_date":   invoice_date,
		"due_date":       due_date,
		"payment_status": payment_status,
	})

	if err != nil {
		fmt.Println(err)
		return ctx.Error(500, "Internal Server Error")
	}

	if status != 200 {
		fmt.Println(status)
		return ctx.Error(500, "Internal Server Error")
	}

	return status, invoice, nil
