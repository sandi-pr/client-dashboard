func CreateIndustry(ctx *config.ConfigContext) (int, U.Dict, *config.ReturnHTTPError) {
	bearer, bearer_ok := ctx.Headers.GetString("Authorization")

	if !bearer_ok {
		return ctx.Error(401, "Unauthorized")
	}

	Strapi := strapi.NewStrapiWithToken(STRAPI_URL, strings.Replace(string(bearer), "Bearer ", "", 1))

	status, me, err := Strapi.UsersMe()
	if err != nil {
		fmt.Println(err)
		return ctx.Error(500, "Internal Server Error")
	}

	if status != 200 {
		fmt.Println(status)
		return ctx.Error(500, "Internal Server Error")
	}

	fmt.Println(me)

	industry_name, ok := ctx.Params.GetString("industry_name")
	if !ok {
		return ctx.Error(400, "invalid parameters industry_name")
	}

	industry_description, ok := ctx.Params.GetString("industry_description")
	if !ok {
		industry_description = ""
	}

	if industry_description == "" {
		status, industry, err := Strapi.Create("industries-table", U.Dict{
			"industry_name": industry_name,
		})

		if err != nil {
			fmt.Println(err)
			return ctx.Error(500, "Internal Server Error")
		}

		if status != 200 {
			fmt.Println(status)
			return ctx.Error(500, "Internal Server Error")
		}

		return 200, industry, nil

	} else {
		status, industry, err := Strapi.Create("industries-table", U.Dict{
			"industry_name":        industry_name,
			"industry_description": industry_description,
		})

		if err != nil {
			fmt.Println(err)
			return ctx.Error(500, "Internal Server Error")
		}

		if status != 200 {
			fmt.Println(status)
			return ctx.Error(500, "Internal Server Error")
		}

		return 200, industry, nil
	}
}

